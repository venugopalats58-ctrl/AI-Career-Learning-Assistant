# ==========================================
# SKILL NAME NORMALIZATION
# ==========================================

def normalize_skill(skill):

    return str(skill).strip().lower()


# ==========================================
# GENERATE COMPLETE LEARNING ROADMAP
# ==========================================

def generate_roadmap(missing_skills):

    roadmap = []

    seen_skills = set()

    for skill in missing_skills:

        skill = str(skill).strip()

        if not skill:
            continue

        skill_key = normalize_skill(skill)

        # Avoid duplicate skills
        if skill_key in seen_skills:
            continue

        seen_skills.add(skill_key)

        # Find matching skill in roadmap database
        matched_skill = next(
            (
                name for name in ROADMAP_DATA
                if normalize_skill(name) == skill_key
            ),
            None
        )

        if matched_skill:

            roadmap.append({
                "skill": matched_skill,
                "level": ROADMAP_DATA[matched_skill]["level"],
                "topics": ROADMAP_DATA[matched_skill]["topics"]
            })

        else:

            roadmap.append({
                "skill": skill,
                "level": "Beginner",
                "topics": [
                    f"Introduction to {skill}",
                    f"{skill} Fundamentals",
                    f"Important Concepts in {skill}",
                    f"Practical Examples of {skill}",
                    f"Advanced Concepts in {skill}",
                    f"Build a Real-World Project using {skill}"
                ]
            })

    return roadmap
